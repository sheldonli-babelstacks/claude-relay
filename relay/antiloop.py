"""防回环：relay 唤醒的会话自己又去评论 Jira／GitHub，评论又触发 webhook——不挡住会无限循环。

两道闸：
1. 逐事件过滤：作者黑名单 + 正文特征（relay 唤醒出来的会话几类典型开头：
   「角色｜姓名」首行、工具自动加的 "Generated by Claude Code" 署名）。
2. 全局熔断：前两道都没挡住的未知回环，用「窗口内全局唤醒数」兜底，超了就全局暂停，
   需要人工 reset_circuit_breaker 才能恢复——不自动恢复，因为自动恢复等于没有熔断。
"""
from __future__ import annotations

import re

from .config import AntiLoopConfig
from .state import State


def looks_self_generated(body_text: str, author_id: str | None, cfg: AntiLoopConfig) -> str | None:
    """命中任一规则就返回原因字符串（真值）；没命中返回 None。"""
    if author_id and author_id in cfg.ignore_authors:
        return f"author {author_id} 在 ignore_authors 黑名单里"
    for pattern in cfg.ignore_body_patterns:
        if re.search(pattern, body_text or "", flags=re.MULTILINE):
            return f"正文命中 ignore_body_patterns: {pattern!r}"
    return None


class CircuitBreakerOpen(RuntimeError):
    pass


def check_and_record_wake(state: State, route_name: str, cfg: AntiLoopConfig) -> None:
    """唤醒之前必须调用。熔断已跳闸时直接抛异常，不执行唤醒。"""
    tripped = state.circuit_breaker_tripped()
    if tripped:
        raise CircuitBreakerOpen(f"熔断已跳闸（{tripped}），需要人工 reset 才能恢复")

    count = state.global_wake_count(cfg.circuit_breaker_window_seconds)
    if count >= cfg.circuit_breaker_max_wakes:
        reason = (
            f"{cfg.circuit_breaker_window_seconds}s 内全局唤醒数达到 {count}，"
            f"超过阈值 {cfg.circuit_breaker_max_wakes}，疑似回环"
        )
        state.trip_circuit_breaker(reason)
        raise CircuitBreakerOpen(reason)

    state.record_wake(route_name)
